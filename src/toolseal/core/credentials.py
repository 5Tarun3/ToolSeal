"""Credential provisioning: the remediation behind check family A.

The rule this module exists to enforce is that **a credential value never
reaches disk**. Quickstarts universally instruct the reader to paste a live key
into `.env`, and that file then outlives the tutorial, gets copied between
machines, and eventually gets committed. Storing the value in the OS keychain
and leaving only its *name* in the project removes the artifact entirely.

Named ``credentials`` rather than ``secrets`` deliberately: a module named
``secrets`` inside this package invites confusion with the standard library
module of that name, and confusion in the module that handles keys is expensive.

Failure is loud by design. When no keychain backend exists - a headless CI box,
typically - :class:`KeyringStore` refuses rather than silently falling back to a
file. A security tool that quietly degrades to the insecure path is worse than
one that stops, because the user believes they are protected.
"""

from __future__ import annotations

import os
import re
from enum import StrEnum
from typing import Final, Protocol

from toolseal.errors import ConfigError

SERVICE_NAME: Final = "toolseal"

# Prefix for the environment backend's variables. Namespaced so that a value
# toolseal is expected to resolve cannot be confused with whatever else the
# deployment happens to export.
ENV_PREFIX: Final = "TOOLSEAL_CREDENTIAL_"

# Pinned exactly, matching this project's own dependency. A generated project
# that resolves its credential from the keychain at runtime (`agent.py`) needs
# `keyring` itself; this is the one place both the scaffolder and the
# scaffolded project's `requirements.txt` get the version from, so they cannot
# drift apart.
KEYRING_PACKAGE_PIN: Final = "keyring==25.7.0"

# Backends that exist only to raise when used. `keyring` selects one of these
# when the platform offers no real credential store.
NULL_BACKENDS: Final[frozenset[str]] = frozenset({"keyring.backends.fail.Keyring"})

# Lines a project needs so that credential-bearing files cannot be committed.
# Order is stable so a regenerated .gitignore diffs empty.
GITIGNORE_ENTRIES: Final[tuple[str, ...]] = (
    ".env",
    ".env.*",
    "!.env.example",
    "*.pem",
    "*.key",
    "credentials.json",
)

GITIGNORE_HEADER: Final = "# Credential files - added by toolseal (checks A1, A2)"

# Minimal hook set for a generated project. detect-private-key is the one that
# matters here; the rest keep the hook file from being the only thing running.
#
# The local `toolseal-policy-verify` hook (P48, spec §8) is safe to ship
# unconditionally: `toolseal policy verify` exits 0 with nothing to report
# until the project has run `toolseal policy enforce` at least once, so this
# does not fail a commit on a project that has never sealed a policy. Once a
# lock does exist, this is what catches a hand-edited `toolseal.toml` or a
# directly-edited `.toolseal/policy.lock` before it is ever pushed - the
# pre-commit half of `verify` being "tamper-evident, checked in two places",
# CI being the other and the one that actually holds.
PRECOMMIT_CONFIG: Final = """\
# Generated by toolseal. `pre-commit install` activates these.
repos:
  - repo: https://github.com/pre-commit/pre-commit-hooks
    rev: v5.0.0
    hooks:
      - id: detect-private-key   # A2: refuse a commit carrying key material
      - id: check-added-large-files
      - id: end-of-file-fixer
      - id: trailing-whitespace
  - repo: local
    hooks:
      - id: toolseal-policy-verify
        name: toolseal policy verify (tamper-evident, not tamper-proof)
        description: >-
          Re-derives the resolved policy and compares it against
          .toolseal/policy.lock, if one exists. A no-op until the project
          runs `toolseal policy enforce`.
        entry: toolseal policy verify
        language: system
        pass_filenames: false
        always_run: true
"""

# Values that look like a placeholder rather than a real credential. Storing one
# of these means the user pasted the example, and they will get a confusing
# authentication error much later if it is accepted here.
_PLACEHOLDER = re.compile(
    r"^\s*(|<.*>|your[-_ ]?(api[-_ ]?)?key.*|xxx+|change[-_ ]?me|todo|\.\.\.)\s*$",
    re.IGNORECASE,
)


class Posture(StrEnum):
    """How well a store protects what it holds.

    Supporting a backend is not a claim that it is as good as the others, and a
    report that listed both without distinguishing them would imply exactly
    that. The difference travels as data on the store so it cannot be dropped
    by whoever renders the report.
    """

    STRONG = "strong"
    WEAKER = "weaker"


class CredentialStore(Protocol):
    """Somewhere a credential can live that is not the project directory."""

    name: str
    posture: Posture
    """How well this store protects the value, for reporting."""
    posture_note: str
    """One clause naming the concrete exposure, for the audit report."""

    def available(self) -> bool:
        """Whether this store can actually be used on this machine."""
        ...

    def set(self, account: str, value: str) -> None: ...

    def get(self, account: str) -> str | None: ...

    def delete(self, account: str) -> None: ...


class KeyringStore:
    """The OS keychain, via ``keyring``.

    Windows Credential Manager, macOS Keychain, or Secret Service on Linux.
    ``keyring`` selects the backend; this class only decides whether the one it
    selected is real.
    """

    name: Final = "os-keychain"
    posture: Final = Posture.STRONG
    posture_note: Final = (
        "the OS keychain holds the value outside the project directory and "
        "outside the process environment"
    )

    def __init__(self, service: str = SERVICE_NAME) -> None:
        self._service = service

    def available(self) -> bool:
        """True when a usable backend is present.

        ``keyring`` installs a null backend when nothing real is found, and that
        backend raises on use rather than reporting itself as absent, so the
        check has to inspect what was selected.

        Identified by qualified name rather than ``isinstance``. Importing the
        null backend's class here would be a second import of ``keyring``, and
        the two could resolve differently - which is exactly the bug that made
        an available keychain report itself as missing.
        """
        try:
            import keyring
        except ImportError:
            return False

        backend = keyring.get_keyring()
        qualified = f"{type(backend).__module__}.{type(backend).__qualname__}"
        if qualified in NULL_BACKENDS:
            return False

        # A chainer with nothing in it behaves like the null backend.
        children = getattr(backend, "backends", None)
        return not (children is not None and not list(children))

    def backend_name(self) -> str | None:
        """The keychain backend `keyring` would use, for diagnostics (`doctor`).

        Returns ``None`` when `keyring` is not importable at all, distinct from
        `available()` returning ``False`` for a real-but-null backend - `doctor`
        reports the two differently.
        """
        try:
            import keyring
        except ImportError:
            return None
        return type(keyring.get_keyring()).__qualname__

    def _require_backend(self) -> None:
        if not self.available():
            message = (
                "no OS keychain is available on this machine, so the credential "
                "cannot be stored securely. Set the value in the environment "
                "instead of having toolseal write it to a file."
            )
            raise ConfigError(message)

    def set(self, account: str, value: str) -> None:
        """Store *value*. Rejects placeholders and blanks before they are saved."""
        self._require_backend()
        if is_placeholder(value):
            message = (
                f"the value given for {account!r} looks like a placeholder rather than "
                "a credential; nothing was stored"
            )
            raise ConfigError(message)

        import keyring

        try:
            keyring.set_password(self._service, account, value)
        except Exception as exc:
            # Deliberately does not include the exception's text: some backends
            # echo the value they were handed.
            message = f"the OS keychain refused to store {account!r} ({type(exc).__name__})"
            raise ConfigError(message) from None

    def get(self, account: str) -> str | None:
        self._require_backend()
        import keyring

        try:
            return keyring.get_password(self._service, account)
        except Exception as exc:
            message = f"the OS keychain refused to read {account!r} ({type(exc).__name__})"
            raise ConfigError(message) from None

    def delete(self, account: str) -> None:
        self._require_backend()
        import keyring

        try:
            keyring.delete_password(self._service, account)
        except Exception:
            # Deleting something already absent is the desired end state.
            return


class EnvironmentStore:
    """Credentials supplied by the process environment.

    The backend a deployed agent can actually use. A container has no keychain
    and a systemd unit has no unlocked session, so the environment is where a
    secret manager, an orchestrator or a CI runner puts a value on its way in.

    **This store is deliberately read-only.** ``os.environ`` can be assigned,
    but the assignment reaches only this process and children it spawns
    afterwards; nothing survives the process exiting. A ``set()`` that appeared
    to succeed and silently persisted nothing is the same class of lie as a
    keychain degrading to plaintext, so both ``set`` and ``delete`` refuse and
    name what to do instead. The value arrives from outside or it does not
    arrive.

    It is also genuinely weaker than the keychain, which :attr:`posture` says
    out loud: an environment variable is readable by every child process and by
    anything that can enumerate the process table.
    """

    name: Final = "environment"
    posture: Final = Posture.WEAKER
    posture_note: Final = (
        "an environment variable is visible to every child process and to "
        "anything that can read the process table"
    )

    def __init__(self, prefix: str = ENV_PREFIX) -> None:
        self._prefix = prefix

    def available(self) -> bool:
        """Always true: every process has an environment.

        This reports *reachability*, not strength. :attr:`posture` is what says
        this store is the weaker of the two, and the two questions are kept
        apart on purpose - conflating them is how "it works here" turns into
        "it is fine here".
        """
        return True

    def variable_for(self, account: str) -> str:
        """The environment variable *account* is read from.

        Provider ids are lowercase and may hyphenate; environment variables
        conventionally do neither, so the name is normalised rather than
        requiring the deployer to guess which spelling is expected.
        """
        suffix = account.strip().upper().replace("-", "_")
        return f"{self._prefix}{suffix}"

    def get(self, account: str) -> str | None:
        value = os.environ.get(self.variable_for(account))
        # An unset variable and one exported empty mean the same thing here. A
        # deployment that exported nothing has not supplied a credential, and
        # returning "" would push the failure to whatever tries to
        # authenticate with it.
        return value or None

    def set(self, account: str, value: str) -> None:
        # Deliberately does not include *value*: an error message is one of the
        # places credentials leak into logs and support tickets.
        message = (
            f"the environment backend cannot store {account!r}: assigning a variable "
            "here would last only as long as this process. Set "
            f"{self.variable_for(account)} in your deployment platform's secret "
            "configuration instead."
        )
        raise ConfigError(message)

    def delete(self, account: str) -> None:
        message = (
            f"the environment backend cannot remove {account!r}: unset "
            f"{self.variable_for(account)} where it is configured."
        )
        raise ConfigError(message)


def is_placeholder(value: str) -> bool:
    """Whether *value* is an example rather than a credential."""
    return _PLACEHOLDER.match(value) is not None


def merge_gitignore(existing: str) -> str:
    """Add the credential ignore rules to *existing*, idempotently.

    Rewriting the file wholesale would discard a user's own rules, and appending
    unconditionally would grow a duplicate block on every run. Only genuinely
    missing lines are added.
    """
    present = {line.strip() for line in existing.splitlines()}
    missing = [entry for entry in GITIGNORE_ENTRIES if entry not in present]
    if not missing:
        return existing

    prefix = existing if existing.endswith("\n") or not existing else existing + "\n"
    block = "\n".join([GITIGNORE_HEADER, *missing])
    separator = "\n" if prefix else ""
    return f"{prefix}{separator}{block}\n"


def environment_reference(env_var: str) -> str:
    """The `.env.example` line for *env_var*: a name, never a value."""
    return f"{env_var}="
